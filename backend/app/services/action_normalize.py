_GROUP = {canon: grp for canon, grp, _ in _RULES}


def canonicalize_action(name: str | None) -> str | None:
    """Canonical action for a raw/vocab action name, or None (route/meta junk OR
    not-yet-covered tail). Action keyword rules take precedence over the DROP list."""
    if not name:
        return None
    t = name.strip().lower()
    for canon, _grp, kws in _RULES:
        for kw in kws:
            if kw in t:
                return canon
    for d in _DROP:
        if d in t:
            return None
    return None


def action_group(canon: str | None) -> str | None:
    return _GROUP.get(canon) if canon else None
