import type { Metadata } from "next";
import Link from "next/link";
import { Header, Footer } from "../ui";
import { Crumbs } from "../../components/common";
import { DEFAULT_OG, SITE_URL, fmtInt, getJson, pluralRu } from "../../lib/api";
import { getLibraryStats } from "../../lib/api-library";
import "./about.css";

// О проекте и о том, как собраны данные атласа: откуда факты, как их проверяют, чему можно
// верить и чему нет. Числа берутся из бэкенда, чтобы страница не устаревала.

const title = "О проекте и методике";
const description =
  "Как собран атлас «Что растёт»: из каких книг взяты сведения, как каждая запись подкреплена дословной цитатой и страницей книги, как названия сведены к видам и где у атласа границы.";

export const metadata: Metadata = {
  title,
  description,
  alternates: { canonical: `${SITE_URL}/about` },
  openGraph: { title, description, url: `${SITE_URL}/about`, type: "article", images: [DEFAULT_OG] },
};

export default async function AboutPage() {
  const [stats, plants, recipes] = await Promise.all([
    getLibraryStats(),
    getJson<{ total: number }>(`/plants/sitemap?limit=1`, 21600, 30000),
    getJson<{ total: number }>(`/recipes/sitemap?limit=1`, 21600, 30000),
  ]);
  const books = stats?.books ?? null;
  const years = stats?.year_min && stats?.year_max ? ` с ${stats.year_min} по ${stats.year_max} год` : "";

  return (
    <>
      <Header />
      <Crumbs items={[{ label: title }]} />
      <main className="prose about">
        <h1>Как собран атлас «Что растёт»</h1>

        <p className="lead">
          «Что растёт» это справочник по растениям и грибам, собранный из старых и не очень старых книг.
          {books ? ` В его основе ${fmtInt(books)} ${pluralRu(books, "книга", "книги", "книг")}${years}: ` : " В его основе "}
          травники, народные лечебники, поваренные книги, определители и справочники по химическому составу растений.
        </p>

        <h2>Что есть в атласе</h2>
        <p>
          Из книг выписаны сведения о том, от чего растение применяли, какие вещества в нём находили, когда и какую часть
          его собирали, чем оно ядовито и что из него готовили.
          {plants?.total ? ` Сейчас в атласе ${fmtInt(plants.total)} ${pluralRu(plants.total, "вид", "вида", "видов")} с фотографией и проверенным названием.` : ""}
          {recipes?.total ? ` Рядом лежат ${fmtInt(recipes.total)} ${pluralRu(recipes.total, "домашний рецепт", "домашних рецепта", "домашних рецептов")}, записанных по шагам.` : ""}
        </p>
        <p>
          У каждого факта указаны книга и год, а у большинства ещё и страница. Ссылка на страницу открывает её в{" "}
          <Link href="/library">библиотеке</Link>, так что любую запись можно сверить с книгой.
        </p>

        <h2>Как книга превращается в карточку растения</h2>
        <p>
          Сначала книгу оцифровывают. Каждая страница сканируется, машина распознаёт её текст, и текст каждой страницы
          хранится отдельно.
        </p>
        <p>
          Потом языковая модель читает страницу и выписывает из неё записи: какое растение названо, от чего его
          применяли, какую часть собирали, в какой срок и как готовили. К каждой записи модель обязана приложить
          дословную цитату. Цитату затем ищут в тексте страницы. Если она там есть, запись подтверждена и получает номер
          страницы. Так отсеиваются записи, которые модель могла додумать.
        </p>
        <p>
          Одно и то же растение в разных книгах называется по-разному: по губерниям, по старым справочникам, с латынью,
          которая менялась от издания к изданию. Поэтому каждую запись привязывают к виду по латинскому названию и сверяют
          его с современными ботаническими базами GBIF и iNaturalist. Старые названия болезней связаны с современными,
          и растения, которые применяли от водянки, найдутся и по слову «отёки».
        </p>
        <p>
          Съедобность и ядовитость оценены по всем записям о виде по шкале из пяти ступеней, от «нет данных» до
          «смертельно ядовито». Когда книги расходятся, берётся более опасная ступень. Если у съедобного растения есть
          ядовитый двойник, он назван в карточке.
        </p>
        <p>
          Фотографии видов взяты из iNaturalist и Викимедиа. Под каждой подписаны автор и лицензия.
        </p>

        <h2>Какие книги открыты целиком</h2>
        <p>
          Книги, изданные до 1917 года, открыты в библиотеке целиком: срок авторских прав на них истёк, и каждую страницу
          можно открыть сканом. У более поздних книг видны описание, номера страниц и цитаты, которые вошли в атлас.
          {stats?.open_books ? ` Сейчас целиком открыты ${fmtInt(stats.open_books)} ${pluralRu(stats.open_books, "книга", "книги", "книг")}.` : ""}
        </p>

        <h2>Чему атлас не учит</h2>
        <p>
          Атлас пересказывает, что писали книги, и не советует, чем лечиться. Многие старые средства оказались
          бесполезными или опасными, а медицина с тех пор изменилась. Записи извлечены машиной и проверены по цитатам,
          но ошибка в отдельной записи возможна. Поэтому у каждой записи есть ссылка на книгу: по ней её можно проверить.
        </p>
        <p>
          Если нужен совет о лечении, спрашивай врача. Если собираешься есть найденное растение или гриб, сначала
          проверь по карточке, чем он опасен и с чем его путают.
        </p>

        <h2>Приложение</h2>
        <p>
          Тот же атлас есть в приложении «Что растёт» для телефона. Оно определяет растение по фотографии и показывает, что
          растёт рядом. Ссылки на приложение стоят в меню «Приложение» вверху страницы.
        </p>

        <p className="footnote">
          Разделы сайта: <Link href="/atlas">атлас</Link>, <Link href="/recipes">рецепты</Link>,{" "}
          <Link href="/library">библиотека</Link>, <Link href="/reference">справочники</Link> и{" "}
          <Link href="/season">календарь сбора</Link>.
        </p>
      </main>
      <Footer />
    </>
  );
}
